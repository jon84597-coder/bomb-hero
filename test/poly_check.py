# 多邊形檢查：把目前的主體輪廓多邊形畫在原圖上（縮到 760 寬），方便目視修正
import os
import numpy as np
import cv2

ART = os.path.join(os.path.dirname(__file__), '..', 'art')
POLY = {
    'boss': [
        (.505, .045), (.575, .075), (.605, .105), (.612, .145), (.600, .195), (.640, .225),
        (.700, .265), (.728, .340), (.740, .450), (.726, .535), (.690, .585), (.665, .620),
        (.700, .645), (.760, .660), (.775, .745), (.735, .790), (.680, .775), (.665, .840),
        (.620, .890), (.560, .900), (.505, .820), (.450, .900), (.390, .880), (.372, .820),
        (.360, .700), (.340, .650), (.338, .560), (.330, .470), (.320, .400), (.322, .300),
        (.352, .235), (.392, .195), (.408, .145), (.420, .100), (.455, .065)],
    'dragon': [
        (.262, .420), (.310, .300), (.352, .245), (.372, .185), (.400, .150), (.435, .118),
        (.500, .112), (.528, .150), (.545, .190), (.548, .265), (.578, .310), (.618, .290),
        (.668, .300), (.742, .390), (.716, .500), (.668, .560), (.660, .640), (.700, .700),
        (.712, .790), (.660, .830), (.600, .870), (.560, .890), (.420, .890), (.372, .860),
        (.356, .760), (.352, .660), (.320, .580), (.268, .520)],
}
for name, pts in POLY.items():
    img = cv2.imread(os.path.join(ART, name + '-src.jpg'))
    h, w = img.shape[:2]
    poly = np.array([[int(x * w), int(y * h)] for x, y in pts], np.int32)
    ov = img.copy()
    cv2.fillPoly(ov, [poly], (0, 255, 255))
    img = cv2.addWeighted(ov, .28, img, .72, 0)
    cv2.polylines(img, [poly], True, (0, 0, 255), 3)
    for i, (x, y) in enumerate(poly):
        cv2.circle(img, (x, y), 7, (0, 0, 255), -1)
        cv2.putText(img, str(i), (x + 9, y - 6), cv2.FONT_HERSHEY_SIMPLEX, .62, (0, 0, 0), 3)
        cv2.putText(img, str(i), (x + 9, y - 6), cv2.FONT_HERSHEY_SIMPLEX, .62, (255, 255, 255), 1)
    out = cv2.resize(img, (760, int(760 * h / w)))
    cv2.imwrite(os.path.join(ART, '_poly_' + name + '.png'), out)
    print(name, 'ok')
